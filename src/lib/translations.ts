export function getLocalizedName(
  item: { name_en: string; name_te?: string | null; name_hi?: string | null },
  lang: Language
): string {
  if (lang === 'te' && item.name_te) return item.name_te;
  if (lang === 'hi' && item.name_hi) return item.name_hi;
  return item.name_en;
}